MAX_VARIANTS = 2


def augment(base, label, n=MAX_VARIANTS):
    variants = {base}
    for _ in range(n * 3):
        if len(variants) >= n:
            break
        intro = random.choice(INTRO)
        end = "" if base.endswith("?") else random.choice(END[label])
        variants.add(f"{intro}{base}{end}")
    return list(variants)

